const URLParams = new URLSearchParams(window.location.search);
const CharacterName = URLParams.get("character"); 
const skins = SkinList[CharacterName];

const title = document.getElementById("char");
title.textContent = "Character: "+CharacterName;

const Owned = document.getElementById('Owned');
const NotOwned = document.getElementById('NotOwned');

function line_trim(line){
  return line.trim();
}
function line_empty(line){
  return line.length > 0;
}
const lines = skins.split("\n").map(line_trim).filter(line_empty);
lines.forEach(function(line){
    const parts = line.split(",").map(line_trim);
    const name = parts[0];
    const group = parts[1];
    const own = parts[2];
    function AddLi(Owning){
        const GroupTitle = document.getElementById(Owning+group+"_t");
        const ul = document.getElementById(Owning+group);
        if (getComputedStyle(GroupTitle).display === "none"){
            GroupTitle.style.display = "flex";
            ul.style.display = "flex";
        }
        const li = document.createElement("li");
        li.textContent = "• "+name;
        ul.appendChild(li);
    }
    let YesOn = false;
    let NoOn = false;
    if (own == "true"){
        if (YesOn == false){
            YesOn = true;
            Owned.style.display = "block";
        }
        AddLi("Y");
    }else{
        if (NoOn == false){
            NoOn = true;
            NotOwned.style.display = "block";
        }
        AddLi("NO");
    }
})